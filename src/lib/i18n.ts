// Helper function to get translation
export function t(key: string, locale: Locale = 'ru'): string {
  const localeData = translations[locale];
  if (!localeData) return key;
  
  // Try direct key lookup first (flat keys like 'common.calculate')
  if (key in localeData) {
    const value = (localeData as Record<string, unknown>)[key];
    if (typeof value === 'string') return value;
  }
  
  // Fallback: try nested key resolution
  const keys = key.split('.');
  let value: unknown = localeData;
  
  for (const k of keys) {
    if (value && typeof value === 'object' && k in value) {
      value = (value as Record<string, unknown>)[k];
    } else {
      return key; // Return key if translation not found
    }
  }
  
  return typeof value === 'string' ? value : key;
}

// Get current locale from localStorage or default
export function getCurrentLocale(): Locale {
  if (typeof window === 'undefined') return defaultLocale;
  const stored = localStorage.getItem('locale');
  if (stored && (stored === 'ru' || stored === 'en')) {
    return stored;
  }
  return defaultLocale;
}

// Set locale and save to localStorage
export function setLocale(locale: Locale): void {
  if (typeof window === 'undefined') return;
  localStorage.setItem('locale', locale);
  document.documentElement.lang = locale;
}

/** @deprecated Use toLocale() instead — identical function */
export const getLocaleForFormatting = toLocale;

// Format a number according to the current locale
export function formatNumber(value: number, locale: Locale, options?: Intl.NumberFormatOptions): string {
  return new Intl.NumberFormat(getLocaleForFormatting(locale), options).format(value);
}

// Format a date according to the current locale
export function formatDate(date: Date | string, locale: Locale, options?: Intl.DateTimeFormatOptions): string {
  const d = typeof date === 'string' ? new Date(date) : date;
  return new Intl.DateTimeFormat(getLocaleForFormatting(locale), options).format(d);
}